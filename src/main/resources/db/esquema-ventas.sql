-- Ejecutar como administrador de PostgreSQL.
CREATE USER ventas_app WITH PASSWORD 'cambiar_esta_contrasena';
CREATE DATABASE ventas_db OWNER ventas_app;

\connect ventas_db

CREATE TABLE IF NOT EXISTS pedidos (
    operacion_id UUID PRIMARY KEY,
    cliente_id INTEGER NOT NULL CHECK (cliente_id > 0),
    total NUMERIC(12,2) NOT NULL CHECK (total > 0),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','CONFIRMADO','CANCELADO')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pedido_lineas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion_id UUID NOT NULL REFERENCES pedidos(operacion_id) ON DELETE CASCADE,
    producto_id INTEGER NOT NULL CHECK (producto_id > 0),
    nombre_producto VARCHAR(120) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario > 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal > 0),
    CONSTRAINT uq_pedido_producto UNIQUE (operacion_id, producto_id)
);

CREATE INDEX IF NOT EXISTS idx_pedidos_cliente ON pedidos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_estado ON pedidos(estado);

GRANT CONNECT ON DATABASE ventas_db TO ventas_app;
GRANT USAGE ON SCHEMA public TO ventas_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ventas_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ventas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ventas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT USAGE, SELECT ON SEQUENCES TO ventas_app;
